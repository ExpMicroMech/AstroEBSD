def modify_mc(filename: str, simfolder: Path, params: dict) -> None:
    """modify_mc  This function is supposed, to auto-generate a monte-carlo nml for to be use by the EMMCOpenCL skript.
        The params are all parameters as sepcified in the emsoft wiki or as can be generated by EMMCOpenCL -t

        TODO: Refactor, that modify_mc , modify_bethe and modify_master are merged into one function

    Args:
        filename (Path): Name of the .nml file
        simfolder (Path): output folder for the .nml file
        params (dict): Dict containing the emsoft style parameters list
    """
    nml = f90nml.read(f"{simfolder.joinpath(filename.stem)}_mc.nml")
    for key in params.keys():
        nml["mccldata"][key] = params[key]
    nml.write(f"{simfolder.joinpath(filename.stem)}_mc.nml", "w")


