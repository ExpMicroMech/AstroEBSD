def setup_folder_structure(filename: str, params: dict) -> Path:
    """setup_folder_structure _summary_

    Args:
        filename (str): _description_
        params (dict): _description_

    Returns:
        chempath (Path): Folder, in which all the .nml (and also .sh files used by the different EM programms are used.)
    """

    Path(get_emdatapath()).joinpath(filename.stem).mkdir(parents=True, exist_ok=True)
    chempath = Path(get_emdatapath()).joinpath(filename.stem)
    if "ekev" in params["mc"].keys():
        chempath.joinpath(f"{(params['mc']['ekev']):.3f}kV").mkdir(
            parents=True, exist_ok=True
        )
        chempath = chempath.joinpath(f"{(params['mc']['ekev']):.3f}kV")
    else:
        chempath.joinpath("default_voltage").mkdir(parents=True, exist_ok=True)
        chempath = chempath.joinpath("default_voltage")
    param_names = ["dmin", "c1", "c2", "ehistmin", "npx"]
    append_string = ""
    for check_param in param_names:
        if check_param in params["mc"].keys():
            append_string = (
                f"{append_string}_{check_param}-{(params['mc'][check_param]):.3f}"
            )
        elif check_param in params["master"].keys():
            append_string = (
                f"{append_string}_{check_param}-{(params['master'][check_param]):.3f}"
            )
        elif check_param in params["bethelist"].keys():
            print(params["bethelist"][check_param])
            append_string = f"{append_string}_{check_param}-{(params['bethelist'][check_param]):.3f}"
    chempath = chempath.joinpath(
        f"{str(datetime.now().strftime('%Y_%m_%d__%H_%M_%S'))}{append_string}"
    )
    chempath.mkdir(parents=True, exist_ok=True)
    return chempath
