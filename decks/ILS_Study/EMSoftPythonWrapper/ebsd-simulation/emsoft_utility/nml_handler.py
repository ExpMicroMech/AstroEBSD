def modify_master(filename: str, simfolder: Path, params: dict) -> None:
    """modify_master This function is supposed, to auto-generate a bethe-parameter nml for to be use by the EMEBSDMaster skript.
       The params are all parameters as sepcified in the emsoft wiki or as can be generated by EMEBSDMaster -t

       TODO: Refactor, that modify_mc , modify_bethe and modify_master are merged into one function

    Args:
       filename (Path): Name of the .nml file
       simfolder (Path): output folder for the .nml file
       params (dict): Dict containing the emsoft style parameters list
    """

    nml = f90nml.read(f"{simfolder.joinpath(filename.stem)}_master.nml")
    for key in params.keys():
        nml["ebsdmastervars"][key] = params[key]
    nml.write(f"{simfolder.joinpath(filename.stem)}_master.nml", "w")
    with open(f"{simfolder.joinpath(filename.stem)}_master.nml", "r") as f:
        nml = f.read()
    nml = nml.replace("betheparametersfile", "BetheParametersFile")
    with open(f"{simfolder.joinpath(filename.stem)}_master.nml", "w") as f:
        f.write(nml)


def overwrite_default_mc(filename: str, simfolder: Path) -> None:
    """overwrite_default_mc Load default paramters, that can be specified in the support folder default_config_emsoft.yml file
       This function also reads a complete nml file which was initally generated by the EMMCOpenCL -t programm

    Args:
        filename (str): nml file name
        simfolder (Path): nml save path
    """

    configpath = "./support/default_config_emsoft.yml"
    with open(configpath) as f:
        emsoft_config = yaml.safe_load(f)
    nml = f90nml.read("./support/EMMCOpenCL.nml")

    for key in emsoft_config["mccldata"].keys():
        nml["mccldata"][key] = emsoft_config["mccldata"][key]
    h5FileName = f"{filename.stem}_{simfolder.parents[0].stem}_{simfolder.stem}"
    nml["mccldata"][
        "dataname"
    ] = f"{simfolder.relative_to(get_emdatapath()).joinpath(h5FileName)}.h5"
    nml["mccldata"]["xtalname"] = f"{filename.stem}.xtal"
    nml.write(f"{simfolder.joinpath(filename.stem)}_mc.nml", "w")


